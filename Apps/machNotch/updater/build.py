# Section keyword -> (dot colour, badge label or None)
# We only need the dot colour; section title text comes from the heading as-is.
SECTION_DOT_RULES: list[tuple[tuple[str, ...], str]] = [
    # bug/fix family
    (("bug", "fix"), "#e05f6b"),
    # new/feat family
    (("new", "feat", "feature"), "#7c6ff7"),
    # ui/animation family
    (("ui", "animation", "design", "polish"), "#5b8af7"),
    # perf family
    (("perf", "performance"), "#d4a843"),
    # arch / solid / ddd family
    (("arch", "solid", "ddd", "tech debt", "improvements", "hygiene"), "#e0874a"),
]


def dot_colour_for_section(title: str) -> str:
    lowered = title.lower()
    for keywords, colour in SECTION_DOT_RULES:
        for kw in keywords:
            if kw in lowered:
                return colour
    return "#6b6b8a"  # var(--muted)


@dataclass
class ChangeItem:
    name: str | None   # bolded leader (e.g. "Bazel CI")
    description: str   # remainder; may be empty


@dataclass
class ChangeSection:
    title: str         # raw heading text (with emoji prefix kept)
    items: list[ChangeItem] = field(default_factory=list)
    subsections: list[tuple[str, list[ChangeItem]]] = field(default_factory=list)
    intro: str = ""    # plain paragraph text appearing before any item


@dataclass
class Release:
    version: str       # e.g. "Pre-release" or "[0.1.0]"
    date: str | None   # "2026-01-01" or None
    released: bool     # True if a date is present
    sections: list[ChangeSection] = field(default_factory=list)
    intro: str = ""    # plain paragraph below the H2 (before any H3)


_RELEASE_HEADING_RE = re.compile(
    r"^##\s+(?P<rest>.+?)\s*$"
)
# Match `- **Name**: desc` or `*   **Name**: desc` or bare `- desc`.
_LIST_ITEM_RE = re.compile(r"^[\*\-]\s+(?P<body>.+)$")
_LEADER_RE = re.compile(r"^\*\*(?P<name>[^*]+)\*\*\s*[:\-—]\s*(?P<rest>.+)$")


def parse_release_heading(line: str) -> tuple[str, str | None] | None:
    """
    Return (version, date) for release H2 lines, or None if not a release.

    Accepts:
        ## Pre-release
        ## [0.1.0] — 2026-01-01
        ## [0.1.0] - 2026-01-01
        ## 0.1.0 - 2026-01-01
    Skips:
        ## anything else (e.g. ## Releases header)
    """
    m = _RELEASE_HEADING_RE.match(line)
    if not m:
        return None
    rest = m.group("rest").strip()

    # Plain "Pre-release" (or any text without a date) — accept as unreleased.
    # Heuristic: look for an ISO date.
    date_match = re.search(r"(\d{4}-\d{2}-\d{2})", rest)
    if date_match:
        date = date_match.group(1)
        version = rest[: date_match.start()].strip(" —-").strip()
    else:
        date = None
        version = rest

    # Strip surrounding [] off version
    if version.startswith("[") and version.endswith("]"):
        version = version[1:-1]

    if not version:
        return None
    return version, date


def parse_changelog(md: str) -> list[Release]:
    """Parse the Keep a Changelog file into Release objects."""
    releases: list[Release] = []
    current_release: Release | None = None
    current_section: ChangeSection | None = None
    current_subsection: tuple[str, list[ChangeItem]] | None = None

    lines = md.splitlines()
    i = 0
    in_intro_paragraph = False  # tracks whether we're collecting prose
    while i < len(lines):
        line = lines[i].rstrip()

        # H2 release heading
        if line.startswith("## "):
            parsed = parse_release_heading(line)
            if parsed:
                version, date = parsed
                current_release = Release(
                    version=version,
                    date=date,
                    released=date is not None,
                )
                releases.append(current_release)
                current_section = None
                current_subsection = None
                in_intro_paragraph = False
                i += 1
                continue
            # Non-release H2 (e.g. "# Changelog" preamble already skipped at H1).
            # Treat as a paragraph break and ignore.
            current_section = None
            current_subsection = None
            in_intro_paragraph = False
            i += 1
            continue

        # H1 — ignore (document title)
        if line.startswith("# "):
            i += 1
            continue

        # H3 section
        if line.startswith("### "):
            if current_release is None:
                i += 1
                continue
            title = line[4:].strip()
            current_section = ChangeSection(title=title)
            current_release.sections.append(current_section)
            current_subsection = None
            in_intro_paragraph = False
            i += 1
            continue

        # H4 subsection
        if line.startswith("#### "):
            if current_section is None:
                i += 1
                continue
            sub_title = line[5:].strip()
            current_subsection = (sub_title, [])
            current_section.subsections.append(current_subsection)
            in_intro_paragraph = False
            i += 1
            continue

        # List item
        list_m = _LIST_ITEM_RE.match(line)
        if list_m and current_release is not None:
            body = list_m.group("body").strip()
            leader = _LEADER_RE.match(body)
            if leader:
                item = ChangeItem(
                    name=leader.group("name").strip(),
                    description=leader.group("rest").strip(),
                )
            else:
                item = ChangeItem(name=None, description=body)
            if current_subsection is not None:
                current_subsection[1].append(item)
            elif current_section is not None:
                current_section.items.append(item)
            # Items outside any section are dropped intentionally.
            in_intro_paragraph = False
            i += 1
            continue

        # Horizontal rule / blank — paragraph break
        if not line or line.strip() == "---":
            in_intro_paragraph = False
            i += 1
            continue

        # Plain paragraph text
        if current_release is not None:
            target_attr = None
            if current_section is not None:
                target_attr = "intro" if not current_section.items else None
                if target_attr:
                    existing = current_section.intro
                    current_section.intro = (
                        (existing + " " + line).strip() if existing else line
                    )
                # Else: ignore prose interleaved between items.
            else:
                # Release-level intro (between H2 and first H3)
                existing = current_release.intro
                current_release.intro = (
                    (existing + " " + line).strip() if existing else line
                )
            in_intro_paragraph = True
        i += 1

    return releases


