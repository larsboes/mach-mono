@dataclass
class RoadmapCard:
    title: str
    description: str
    tag: str | None


@dataclass
class RoadmapSection:
    icon: str
    title: str
    kind: str
    cards: list[RoadmapCard] = field(default_factory=list)
    empty_text: str | None = None


ICON_KIND = {
    "↑": "active",
    "⌛": "planned",
    "🚀": "launched",
}

_CARD_HEADING_RE = re.compile(r"^###\s+(?P<title>.+?)(?:\s+\[(?P<tag>[^\]]+)\])?\s*$")
_EMPTY_RE = re.compile(r"^_(.+)_\s*$")


def parse_section_heading(line: str) -> tuple[str, str, str] | None:
    if not line.startswith("## "):
        return None
    rest = line[3:].strip()
    parts = rest.split(None, 1)
    if len(parts) < 2:
        return None
    icon, title = parts[0], parts[1].strip()
    kind = ICON_KIND.get(icon, "other")
    return icon, title, kind


def parse_roadmap(md: str) -> tuple[str, list[RoadmapSection]]:
    meta, body = strip_front_matter(md)
    subtitle = meta.get("subtitle", "")
    sections: list[RoadmapSection] = []
    current_section: RoadmapSection | None = None
    current_card: RoadmapCard | None = None

    for raw_line in body.splitlines():
        line = raw_line.rstrip()
        sec = parse_section_heading(line)
        if sec is not None:
            icon, title, kind = sec
            current_section = RoadmapSection(icon=icon, title=title, kind=kind)
            sections.append(current_section)
            current_card = None
            continue
        card_m = _CARD_HEADING_RE.match(line)
        if card_m and current_section is not None:
            current_card = RoadmapCard(
                title=card_m.group("title").strip(),
                description="",
                tag=(card_m.group("tag") or "").strip() or None,
            )
            current_section.cards.append(current_card)
            continue
        if current_section is not None and not current_section.cards:
            empty_m = _EMPTY_RE.match(line.strip())
            if empty_m:
                current_section.empty_text = empty_m.group(1).strip()
                current_card = None
                continue
        if not line.strip():
            continue
        if current_card is not None:
            text = line.strip()
            current_card.description = (
                (current_card.description + " " + text).strip()
                if current_card.description
                else text
            )

    return subtitle, sections


