def render_decisions_content(adrs: list[ADR]) -> str:
    accepted = sum(1 for a in adrs if a.status_kind == "accepted")
    superseded = len(adrs) - accepted

    parts: list[str] = []
    parts.append('<div class="page-header">')
    parts.append('  <h1>Decisions</h1>')
    parts.append(
        '  <p>Architecture Decision Records — the why behind major technical choices. '
        'Click any entry to expand.</p>'
    )
    parts.append('</div>')
    parts.append('<div class="adr-list-header">')
    parts.append(
        f'  <span class="adr-count">{len(adrs)} records'
        f' · {accepted} accepted'
        + (f' · {superseded} superseded' if superseded else '')
        + '</span>'
    )
    parts.append('</div>')
    for adr in adrs:
        parts.append(render_adr(adr))
    parts.append(_TOGGLE_JS)
    return "\n".join(parts)


