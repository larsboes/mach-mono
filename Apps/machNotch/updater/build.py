def load_template() -> str:
    return TEMPLATE_PATH.read_text(encoding="utf-8")


def render_template(
    *,
    title: str,
    page_style: str,
    active_href: str,
    content: str,
) -> str:
    template = load_template()
    nav_items = render_nav_items(active_href)
    return (
        template
        .replace("{{TITLE}}", title)
        .replace("{{PAGE_STYLE}}", page_style)
        .replace("{{NAV_ITEMS}}", nav_items)
        .replace("{{CONTENT}}", content)
    )


