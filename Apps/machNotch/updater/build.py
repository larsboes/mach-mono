def render_roadmap_card(card: RoadmapCard) -> str:
    title_html = render_inline(card.title)
    desc_html = render_inline(card.description)
    meta_html = ""
    if card.tag:
        meta_html = (
            f'      <div class="rm-card-meta">'
            f'<span class="rm-tag">{html.escape(card.tag)}</span>'
            f'</div>'
        )
    parts = [
        '    <div class="rm-card">',
        '      <div class="rm-card-body">',
        f'        <div class="rm-card-title">{title_html}</div>',
        f'        <div class="rm-card-desc">{desc_html}</div>',
        '      </div>',
    ]
    if meta_html:
        parts.append(meta_html)
    parts.append('    </div>')
    return "\n".join(parts)


def render_roadmap_section(section: RoadmapSection) -> str:
    parts: list[str] = []
    parts.append('<div class="rm-section">')
    parts.append(f'  <div class="rm-label {section.kind}">')
    parts.append(f'    <span class="rm-icon">{html.escape(section.icon)}</span>')
    parts.append(f'    <span class="rm-title">{html.escape(section.title)}</span>')
    parts.append('  </div>')
    parts.append('  <div class="rm-cards">')
    if section.cards:
        for card in section.cards:
            parts.append(render_roadmap_card(card))
    elif section.empty_text:
        parts.append(f'    <div class="rm-empty">{render_inline(section.empty_text)}</div>')
    parts.append('  </div>')
    parts.append('</div>')
    return "\n".join(parts)


def render_roadmap_content(subtitle: str, sections: list[RoadmapSection]) -> str:
    total = launched = 0
    for s in sections:
        n = len(s.cards)
        total += n
        if s.kind == "launched":
            launched += n
    pct = round(launched / total * 100) if total else 0

    parts: list[str] = []
    parts.append('<div class="page-header">')
    parts.append('  <h1>Roadmap</h1>')
    if subtitle:
        parts.append(f'  <p>{render_inline(subtitle)}</p>')
    parts.append('</div>')

    # Progress strip
    parts.append('<div class="rm-progress">')
    parts.append('  <div class="rm-progress-track">')
    parts.append(f'    <div class="rm-progress-fill" style="width:{pct}%"></div>')
    parts.append('  </div>')
    parts.append(
        f'  <span class="rm-progress-label">'
        f'<strong>{launched}</strong> of {total} shipped'
        f'</span>'
    )
    parts.append('</div>')

    for section in sections:
        parts.append(render_roadmap_section(section))
    return "\n".join(parts)


