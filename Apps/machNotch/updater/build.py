def _render_template(
    *,
    template_path: Path,
    title: str,
    page_style: str,
    active_href: str,
    content: str,
    og_title: str = "",
    og_description: str = "",
) -> str:
    template = template_path.read_text(encoding="utf-8")
    nav_items = render_nav_items(active_href)
    og_title = og_title or title
    return (
        template
        .replace("{{TITLE}}", title)
        .replace("{{OG_TITLE}}", html.escape(og_title, quote=True))
        .replace("{{OG_DESCRIPTION}}", html.escape(og_description, quote=True))
        .replace("{{PAGE_STYLE}}", page_style)
        .replace("{{NAV_ITEMS}}", nav_items)
        .replace("{{CONTENT}}", content)
    )


