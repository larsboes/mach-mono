def slugify_version(version: str) -> str:
    slug = re.sub(r'[^\w]', '-', version.lower())
    return re.sub(r'-+', '-', slug).strip('-')


def strip_mermaid_fence(text: str) -> str:
    text = text.strip()
    if text.startswith("```mermaid"):
        text = text[len("```mermaid"):].strip()
    if text.endswith("```"):
        text = text[:-3].strip()
    return text


