def render_blocks(text: str) -> str:
    """Render block-level Markdown (paragraphs, lists, fenced code, tables)."""
    lines = text.splitlines()
    parts: list[str] = []
    i = 0

    while i < len(lines):
        line = lines[i]

        # Fenced code block
        stripped = line.strip()
        if stripped.startswith("```"):
            lang = stripped[3:].strip()
            code_lines: list[str] = []
            i += 1
            while i < len(lines) and not lines[i].strip().startswith("```"):
                code_lines.append(lines[i])
                i += 1
            i += 1  # skip closing fence
            code_content = html.escape("\n".join(code_lines))
            lang_cls = f' class="language-{html.escape(lang)}"' if lang else ''
            parts.append(f'<pre class="adr-pre"><code{lang_cls}>{code_content}</code></pre>')
            continue

        # Table
        if '|' in line and stripped.startswith('|'):
            table_lines: list[str] = []
            while i < len(lines) and '|' in lines[i] and lines[i].strip().startswith('|'):
                table_lines.append(lines[i])
                i += 1
            parts.append(render_table(table_lines))
            continue

        # List items
        if stripped.startswith('- ') or stripped.startswith('* '):
            list_items: list[str] = []
            while i < len(lines) and (
                lines[i].strip().startswith('- ') or lines[i].strip().startswith('* ')
            ):
                list_items.append(lines[i].strip()[2:])
                i += 1
            items_html = ''.join(f'<li>{render_inline(item)}</li>' for item in list_items)
            parts.append(f'<ul class="adr-list">{items_html}</ul>')
            continue

        # Blank line
        if not stripped:
            i += 1
            continue

        # Paragraph — collect until blank line or block element
        para_lines: list[str] = []
        while i < len(lines):
            stripped_line = lines[i].strip()
            if not stripped_line:
                break
            if stripped_line.startswith('```') or (stripped_line.startswith('|') and '|' in stripped_line) or stripped_line.startswith('- ') or stripped_line.startswith('* '):
                break
            para_lines.append(stripped_line)
            i += 1
        if para_lines:
            parts.append(f'<p class="adr-body">{render_inline(" ".join(para_lines))}</p>')

    return '\n'.join(parts)


