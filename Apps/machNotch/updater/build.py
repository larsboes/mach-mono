def render_guide_content(content: GuideContent) -> str:
    parts: list[str] = []

    parts.append('<div class="page-header">')
    parts.append(f'  <h1>{html.escape(content.title)}</h1>')
    if content.subtitle:
        parts.append(f'  <p>{render_inline(content.subtitle)}</p>')
    parts.append('</div>')

    if content.steps:
        parts.append('<div class="steps">')
        parts.append('  <p class="steps-title">Installation</p>')
        for i, step in enumerate(content.steps):
            parts.append('  <div class="step">')
            parts.append(f'    <div class="step-num">{i + 1}</div>')
            parts.append('    <div class="step-body">')
            parts.append(f'      <p class="step-title">{html.escape(step.title)}</p>')
            parts.append(f'      <p class="step-desc">{render_inline(step.description)}</p>')
            parts.append('    </div>')
            parts.append('  </div>')
            if i < len(content.steps) - 1:
                parts.append('  <div class="connector"></div>')
        parts.append('</div>')

    if content.permissions:
        parts.append('<div class="permissions">')
        parts.append('  <p class="permissions-title">Permissions</p>')
        parts.append('  <div class="perm-grid">')
        for perm in content.permissions:
            badge_cls = "perm-required" if perm.required else "perm-optional"
            badge_lbl = "Required" if perm.required else "Optional"
            parts.append('    <div class="perm-card">')
            parts.append(f'      <span class="perm-badge {badge_cls}">{badge_lbl}</span>')
            parts.append('      <div class="perm-info">')
            parts.append(f'        <p class="perm-name">{html.escape(perm.name)}</p>')
            parts.append(f'        <p class="perm-desc">{render_inline(perm.description)}</p>')
            parts.append('      </div>')
            parts.append('    </div>')
        parts.append('  </div>')
        parts.append('</div>')

    if content.tips:
        parts.append('<div class="tips">')
        parts.append('  <p class="tips-title">Tips</p>')
        parts.append('  <ul class="tip-list">')
        for tip in content.tips:
            parts.append(f'    <li class="tip-item"><span>{render_inline(tip.text)}</span></li>')
        parts.append('  </ul>')
        parts.append('</div>')

    if content.cta:
        cta = content.cta
        parts.append('<div class="cta-strip">')
        parts.append('  <div class="cta-text">')
        parts.append(f'    <h3>{html.escape(cta.title)}</h3>')
        parts.append(f'    <p>{render_inline(cta.description)}</p>')
        parts.append('  </div>')
        if cta.link_text and cta.link_href:
            href_esc = html.escape(cta.link_href, quote=True)
            parts.append(f'  <a class="btn-sm" href="{href_esc}">')
            parts.append(f'    {_CTA_SVG}')
            parts.append(f'    {html.escape(cta.link_text)}')
            parts.append('  </a>')
        parts.append('</div>')

    return "\n".join(parts)


