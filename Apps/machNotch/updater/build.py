# ---------------------------------------------------------------------------
# Architecture Decision Records (ADR) parsing & rendering
# ---------------------------------------------------------------------------

@dataclass
class ADR:
    number: str
    title: str
    status_raw: str
    status_kind: str   # "accepted" | "superseded"
    date: str
    sections: dict[str, str]


_ADR_TITLE_RE = re.compile(r'^(\d{4})\s*[—\-]+\s*(.+)$')


def parse_adr(text: str, filename: str = "") -> ADR:
    lines = text.splitlines()
    number = ""
    title = ""
    status_raw = ""
    date = ""
    sections: dict[str, str] = {}
    current_section: str | None = None
    section_lines: list[str] = []

    for line in lines:
        if line.startswith("# "):
            rest = line[2:].strip()
            m = _ADR_TITLE_RE.match(rest)
            if m:
                number = m.group(1)
                title = m.group(2).strip()
            continue
        if line.startswith("- Status:"):
            status_raw = line[9:].strip()
            continue
        if line.startswith("- Date:"):
            date = line[7:].strip()
            continue
        if line.startswith("## "):
            if current_section and section_lines:
                sections[current_section] = "\n".join(section_lines).strip()
            section_lines = []
            current_section = line[3:].strip()
            continue
        if current_section is not None:
            section_lines.append(line)

    if current_section and section_lines:
        sections[current_section] = "\n".join(section_lines).strip()

    # Fall back to filename for number if not parsed from heading
    if not number and filename:
        m2 = re.match(r'^(\d{4})', filename)
        if m2:
            number = m2.group(1)

    status_kind = "superseded" if "superseded" in status_raw.lower() else "accepted"
    return ADR(number=number, title=title, status_raw=status_raw,
                status_kind=status_kind, date=date, sections=sections)


