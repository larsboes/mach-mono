_GUIDE_TAG_RE = re.compile(r"^(.+?)\s*\[([^\]]+)\]\s*$")
_GUIDE_LONE_LINK_RE = re.compile(r"^\[([^\]]+)\]\(([^)]+)\)\s*$")


@dataclass
class GuideStep:
    title: str
    description: str


@dataclass
class GuidePerm:
    name: str
    description: str
    required: bool


@dataclass
class GuideTip:
    text: str


@dataclass
class GuideCTA:
    title: str
    description: str
    link_text: str
    link_href: str


@dataclass
class GuideContent:
    title: str
    subtitle: str
    steps: list[GuideStep] = field(default_factory=list)
    permissions: list[GuidePerm] = field(default_factory=list)
    tips: list[GuideTip] = field(default_factory=list)
    cta: GuideCTA | None = None


def parse_guide(md: str) -> GuideContent:
    meta, body = strip_front_matter(md)
    content = GuideContent(
        title=meta.get("title", "Getting started"),
        subtitle=meta.get("subtitle", ""),
    )

    section_type = ""
    current_step: GuideStep | None = None
    current_perm: GuidePerm | None = None

    for raw_line in body.splitlines():
        line = raw_line.rstrip()

        if line.startswith("## "):
            section_type = line[3:].strip().lower()
            current_step = None
            current_perm = None
            continue

        if line.startswith("### "):
            heading = line[4:].strip()
            current_step = None
            current_perm = None

            if section_type == "installation":
                current_step = GuideStep(title=heading, description="")
                content.steps.append(current_step)

            elif section_type == "permissions":
                tag_m = _GUIDE_TAG_RE.match(heading)
                if tag_m:
                    name = tag_m.group(1).strip()
                    required = tag_m.group(2).strip().lower() == "required"
                else:
                    name = heading
                    required = False
                current_perm = GuidePerm(name=name, description="", required=required)
                content.permissions.append(current_perm)

            elif section_type == "cta" and content.cta is None:
                content.cta = GuideCTA(title=heading, description="", link_text="", link_href="")
            continue

        if not line.strip():
            continue

        if line.startswith("- ") and section_type == "tips":
            content.tips.append(GuideTip(text=line[2:].strip()))
            continue

        lone_link = _GUIDE_LONE_LINK_RE.match(line.strip())
        if lone_link and section_type == "cta" and content.cta is not None:
            content.cta.link_text = lone_link.group(1)
            content.cta.link_href = lone_link.group(2)
            continue

        text = line.strip()
        if section_type == "installation" and current_step is not None:
            current_step.description = (
                (current_step.description + " " + text).strip()
                if current_step.description else text
            )
        elif section_type == "permissions" and current_perm is not None:
            current_perm.description = (
                (current_perm.description + " " + text).strip()
                if current_perm.description else text
            )
        elif section_type == "cta" and content.cta is not None:
            cta = content.cta
            cta.description = (
                (cta.description + " " + text).strip()
                if cta.description else text
            )

    return content


