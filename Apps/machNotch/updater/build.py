_LINK_RE = re.compile(r"\[([^\]]+)\]\(([^)]+)\)")
_BOLD_RE = re.compile(r"\*\*([^*]+)\*\*")
_ITALIC_RE = re.compile(r"(?<![\*_])\*([^*\n]+)\*(?![\*_])")
_CODE_RE = re.compile(r"`([^`]+)`")
_OL_ITEM_RE = re.compile(r"^\d+\.\s+(.+)$")


def render_inline(text: str) -> str:
    """Render inline Markdown to HTML."""
    code_spans: list[str] = []

    def _capture_code(m: re.Match[str]) -> str:
        code_spans.append(m.group(1))
        return f"\x00CODE{len(code_spans) - 1}\x00"

    work = _CODE_RE.sub(_capture_code, text)

    links: list[tuple[str, str]] = []

    def _capture_link(m: re.Match[str]) -> str:
        links.append((m.group(1), m.group(2)))
        return f"\x00LINK{len(links) - 1}\x00"

    work = _LINK_RE.sub(_capture_link, work)
    work = html.escape(work, quote=False)
    work = _BOLD_RE.sub(r"<strong>\1</strong>", work)
    work = _ITALIC_RE.sub(r"<em>\1</em>", work)

    def _restore_link(m: re.Match[str]) -> str:
        idx = int(m.group(1))
        label, href = links[idx]
        label_html = _BOLD_RE.sub(r"<strong>\1</strong>", html.escape(label, quote=False))
        label_html = _ITALIC_RE.sub(r"<em>\1</em>", label_html)
        return f'<a href="{html.escape(href, quote=True)}">{label_html}</a>'

    work = re.sub(r"\x00LINK(\d+)\x00", _restore_link, work)

    def _restore_code(m: re.Match[str]) -> str:
        idx = int(m.group(1))
        return f"<code>{html.escape(code_spans[idx], quote=False)}</code>"

    work = re.sub(r"\x00CODE(\d+)\x00", _restore_code, work)
    return work


