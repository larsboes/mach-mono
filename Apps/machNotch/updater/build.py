def render_change_item(item: ChangeItem) -> str:
    if item.name:
        name_html = render_inline(item.name)
        desc_html = render_inline(item.description)
        return (
            f'      <li class="change-item">'
            f'<strong>{name_html}</strong>: {desc_html}'
            f'</li>'
        )
    desc_html = render_inline(item.description)
    return f'      <li class="change-item">{desc_html}</li>'


def render_change_section(section: ChangeSection) -> str:
    colour = dot_colour_for_section(section.title)
    parts: list[str] = []
    parts.append('  <div class="change-section">')
    parts.append(
        f'    <p class="change-section-title">'
        f'<span class="dot" style="background:{colour}"></span>'
        f'{html.escape(section.title)}</p>'
    )
    if section.intro:
        parts.append(
            f'    <p class="change-section-intro">{render_inline(section.intro)}</p>'
        )
    if section.items:
        parts.append('    <ul class="change-list">')
        for item in section.items:
            parts.append(render_change_item(item))
        parts.append('    </ul>')

    for sub_title, sub_items in section.subsections:
        parts.append(
            f'    <p class="change-subsection-title">{html.escape(sub_title)}</p>'
        )
        if sub_items:
            parts.append('    <ul class="change-list">')
            for item in sub_items:
                parts.append(render_change_item(item))
            parts.append('    </ul>')

    parts.append('  </div>')
    return "\n".join(parts)


def render_release(release: Release) -> str:
    badge_class = "badge-released" if release.released else "badge-unreleased"
    badge_label = "Released" if release.released else "Unreleased"

    parts: list[str] = []
    parts.append('<div class="release">')
    parts.append('  <div class="release-header">')
    parts.append(
        f'    <span class="release-version">{html.escape(release.version)}</span>'
    )
    parts.append(
        f'    <span class="release-badge {badge_class}">{badge_label}</span>'
    )
    if release.date:
        parts.append(
            f'    <span class="release-date">{html.escape(release.date)}</span>'
        )
    parts.append('  </div>')

    if release.intro:
        parts.append(
            f'  <p class="release-intro">{render_inline(release.intro)}</p>'
        )

    for section in release.sections:
        parts.append(render_change_section(section))

    parts.append('</div>')
    return "\n".join(parts)


def render_changelog_content(releases: list[Release]) -> str:
    parts: list[str] = []
    parts.append('<div class="page-header">')
    parts.append('  <h1>Changelog</h1>')
    parts.append(
        '  <p>What&#39;s new in mach.notch — every release, in order. '
        'For upcoming features see the <a href="roadmap.html">Roadmap</a>.</p>'
    )
    parts.append('</div>')
    for release in releases:
        parts.append(render_release(release))
    return "\n".join(parts)


